"""Resize an already-extracted KuRALS dataset (produced by kuralscw_processing.py
or kuralspd_processing.py) down to a smaller RD buffer size, e.g. to match a
deployment SoC's fixed RD memory (given as raw .mat data isn't always available --
only the post-processed range_doppler_numpy/annotations/dense .npy files).

Reuses the same block max-pooling (resize_rd) and bin-lookup remapping used by
kuralscw_processing.py's own --doppler-bins/--range-bins path, so a dataset
generated by either script is numerically identical for the same source frame.

Only range_doppler_numpy/ and annotations/dense/ are processed (the annot_type
actually read by KuRALSDataset -- see kurals/config_files/*.json's "annot_type").
annotations/sparse/ and annotations/box/ are not used by training and are skipped.
Dataset-root JSON/txt files (sequence.txt, annotations.json, rd_stats_all.json,
data_seq_ref.json, light_dataset_frame_oriented.json) are copied unchanged: they
either hold resolution-independent global stats or native-resolution physical-unit
metadata not read as array indices by the training pipeline.
"""
import argparse
import os
import shutil
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from kuralscw_processing import resize_rd, _bin_lookup, NATIVE_DOPPLER_BINS, NATIVE_RANGE_BINS


def resize_mask(mask, doppler_lookup, range_lookup, out_doppler, out_range):
    """Rebuild a (4, native_h, native_w) one-hot dense mask at (4, out_doppler,
    out_range), remapping each foreground pixel through the same bin groups used
    for the signal -- mirrors kuralscw_processing.get_mask's own construction
    (background=1 everywhere, then flipped at the remapped target cells) rather
    than pooling the existing one-hot array per channel, which could leave both
    background and a class simultaneously set to 1 in the same output cell."""
    out = np.zeros((mask.shape[0], out_doppler, out_range))
    out[0] = 1.0
    for c in range(1, mask.shape[0]):
        ys, xs = np.where(mask[c] == 1)
        for y, x in zip(ys, xs):
            oy, ox = doppler_lookup[y], range_lookup[x]
            out[0, oy, ox] = 0.0
            out[c, oy, ox] = 1.0
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--src', required=True, help='Root of the already-extracted dataset (e.g. .../KuRALS_CW).')
    parser.add_argument('--dst', required=True, help='Output root for the resized dataset.')
    parser.add_argument('--doppler-bins', type=int, required=True)
    parser.add_argument('--range-bins', type=int, required=True)
    args = parser.parse_args()

    doppler_lookup = _bin_lookup(NATIVE_DOPPLER_BINS, args.doppler_bins)
    range_lookup = _bin_lookup(NATIVE_RANGE_BINS, args.range_bins)

    os.makedirs(args.dst, exist_ok=True)
    for name in os.listdir(args.src):
        src_path = os.path.join(args.src, name)
        if os.path.isfile(src_path):
            shutil.copy2(src_path, os.path.join(args.dst, name))

    seq_names = [n for n in os.listdir(args.src) if os.path.isdir(os.path.join(args.src, n))]
    for i, seq_name in enumerate(seq_names):
        print(f'[{i+1}/{len(seq_names)}] {seq_name}')
        src_rd_dir = os.path.join(args.src, seq_name, 'range_doppler_numpy')
        dst_rd_dir = os.path.join(args.dst, seq_name, 'range_doppler_numpy')
        os.makedirs(dst_rd_dir, exist_ok=True)
        for fname in os.listdir(src_rd_dir):
            data = np.load(os.path.join(src_rd_dir, fname))
            resized = resize_rd(data, args.doppler_bins, args.range_bins)
            np.save(os.path.join(dst_rd_dir, fname), resized)

        src_dense_dir = os.path.join(args.src, seq_name, 'annotations', 'dense')
        dst_dense_dir = os.path.join(args.dst, seq_name, 'annotations', 'dense')
        if os.path.isdir(src_dense_dir):
            for frame_name in os.listdir(src_dense_dir):
                src_mask_path = os.path.join(src_dense_dir, frame_name, 'range_doppler.npy')
                if not os.path.exists(src_mask_path):
                    continue
                mask = np.load(src_mask_path)
                resized_mask = resize_mask(mask, doppler_lookup, range_lookup, args.doppler_bins, args.range_bins)
                dst_frame_dir = os.path.join(dst_dense_dir, frame_name)
                os.makedirs(dst_frame_dir, exist_ok=True)
                np.save(os.path.join(dst_frame_dir, 'range_doppler.npy'), resized_mask)

    print('Done.')


if __name__ == '__main__':
    main()
