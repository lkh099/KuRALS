"""Write a README.md for a release package from the package's own metadata.

model_release_v01's README was written by hand and the other three packages had none, so the
only machine-readable description of a package was architecture.json's `file_layout` field.
This generates the same document for any package, from config.yaml / metrics.json /
quantization.json / architecture.json -- no numbers are retyped.

  python exp03/make_package_readme.py exp03/model_release_d32_v01
  python exp03/make_package_readme.py exp03/model_release_*    # all of them
"""
import json
import os
import sys

import yaml


def readme(pkg):
    name = os.path.basename(pkg)
    cfg = yaml.safe_load(open(f'{pkg}/config.yaml'))
    met = json.load(open(f'{pkg}/metrics.json'))
    qnt = json.load(open(f'{pkg}/quantization.json'))
    arch = json.load(open(f'{pkg}/architecture.json'))
    pre = json.load(open(f'{pkg}/preprocessing.json'))
    nf, H, W = arch['input_shape']
    nc = arch['n_classes']
    chk = met['npu_check']
    rep, sim = met['exact_integer_replay'], met['qat_float_sim']
    wb = met['weight_bytes']
    n_scale = sum(L['n_scale'] for L in arch['layers'] if 'n_scale' in L)
    n_bias = sum(L['n_bias'] for L in arch['layers'] if 'n_bias' in L)
    peak = max(chk['buf1'], chk['buf2'], chk['buf3'])
    head = '/1 (the head already predicts per-pixel)' if arch['final_upsample'] == 1 else \
           f'/{arch["final_upsample"]} then a bare nearest upsample to /1 (every {arch["final_upsample"]}x{arch["final_upsample"]} output block is identical)'
    agree = rep.get('pixel_agreement_with_qat_sim', 1.0)
    L = [
        f"# {name} -- {cfg['rd_resolution']} KuRALSNetNPUSeg {cfg['width_mult']}x, int8 QAT",
        '',
        f"Generated by `exp03/make_package_readme.py`. Built by `exp03/make_release.py` from run "
        f"`{cfg['source_run']}` (QAT fine-tune of the best-validation FP32 checkpoint "
        f"`{met['fp32_reference_tag']}`, seed {cfg['seed']}, best validation epoch "
        f"{met['best_val_epoch']}). Selection rule: {met['selection_rule']}. Design-point "
        f"rationale: `exp03/summaries/design_point_decision.md`.",
        '',
        '| Item | Value |',
        '|---|---|',
        f"| RD resolution | {cfg['rd_resolution']}: {H} Doppler x {W} range |",
        f"| Tensor order | `(n_frames={nf}, Doppler={H}, Range={W})`, row-major, Doppler in natural FFT order (zero-Doppler at index 0) |",
        f"| Input dtype / scaling | int8 in [0,127]; input_scale = {qnt['input_scale']:g}, no zero point |",
        f"| Input contract | {pre['contract']} |",
        f"| Output | dequantized float32 logits `({nc}, {H}, {W})` from "
        f"{'an unsigned' if qnt['output_unsigned'] else 'a signed'} int8 head "
        f"(output_scale {qnt['output_scale']:.4g}); decode with per-pixel argmax |",
        f"| Output head resolution | {head} |",
        '| Class ordering | 0 background, 1 UAV, 2 and 3 non-UAV channels (see `class_map.json`) |',
        '| Weights | int8, per-channel; hardware weight is `2*w+1`; scales and biases int16 |',
        f"| Model size | {met['params']:,} params; {wb:,} B weights + {n_scale * 2:,} B scales + {n_bias * 2:,} B biases |",
        f"| Complexity | {met['macs'] / 1e6:.2f} M MACs; peak NPU buffer {peak:,} B per bank "
        f"(limit {chk['buf_size']:,} B{', **no headroom**' if peak >= chk['buf_size'] else ''}); "
        f"CUTPOINT {chk['cutpoint']}; {chk['layers']} layers |",
        f"| Architecture | width_mult {cfg['width_mult']}, stem_stride {cfg['stem_stride']}, "
        f"encoder_depth {cfg['encoder_depth']}, bottleneck kernel {cfg['bottleneck_kernel_size']}, "
        f"eltwise_act {cfg['eltwise_act']} |",
        f"| Checksum | SHA-256 of `weights_int.bin` + `scales.bin` + `biases.bin`: `{met['weights_sha256'][:16]}...` (full value in `metrics.json`) |",
        '',
        '## Expected software output',
        '',
        f"`exact_integer_replay` in `metrics.json`: `kurals/int8_inference.py` over the whole "
        f"{cfg['rd_resolution']} Test split gives **test mIoU {rep['test_miou']:.4f}**, per-class IoU "
        f"{[round(v, 4) for v in rep['test_iou_by_class']]}. The QAT training-time simulation gives "
        f"{sim['test_miou']:.4f} and agrees with the integer replay on {agree * 100:.4f} % of pixels. "
        f"**Any hardware run should match the integer replay, not the float simulation.**",
        '',
        'Reproduce it from this package alone, with no checkpoint:',
        '',
        '```bash',
        f'python exp03/load_release.py --package {pkg}            # all 8 samples vs golden_outputs',
        f'python exp03/load_release.py --package {pkg} --sample 0 --layers   # per-layer',
        '```',
        '',
        '## Files',
        '',
        '- `architecture.json` -- layer list in execution order with fused ops, shapes and byte offsets into the three `.bin` files.',
        '- `weights_int.bin`, `scales.bin`, `biases.bin` -- int8 weights, int16 scales, int16 biases '
        '(little-endian). `scales.bin` is an addition to the NPU template tree, kept apart from `biases.bin`.',
        '- `quantization.json`, `preprocessing.json`, `class_map.json`, `config.yaml`, `train_config.json`, `metrics.json`.',
        f'- `sample_inputs/sample_NN_int8.npy` -- 8 Test frames containing a target, shape ({nf}, {H}, {W}), int8, exactly what the NPU reads.',
        f'- `golden_outputs/` -- `logits_f32` ({nc},{H},{W}), `argmax_u8` and `label_u8` ({H},{W}) per sample.',
        '- `golden_layer_outputs/sample_NN.npz` -- every layer\'s dequantized output (float32, real units) from the integer replay, keyed by layer name.',
        '',
        '## Known limits',
        '',
        '- Inputs are block max-pooled from the native map; the SoC computes its own small FFT, so accuracy on silicon data is not established.',
        f"- Class 3 is nearly absent in the data (per-class IoU {rep['test_iou_by_class'][3]:.4f}).",
        '- No measured NPU cycles or latency for this or any other package.',
        f"- Legality was checked with `kurals/npu_check.py`, which runs npu_riscv's `gen_cfg.py` allocator "
        f"(buf1 {chk['buf1']:,} B, buf2 {chk['buf2']:,} B, buf3 {chk['buf3']:,} B against "
        f"{chk['buf_size']:,} B), **not** by a board run.",
    ]
    if arch['final_upsample'] > 1:
        L += ['- This package has a stride-2 stem, so its head predicts at /2 and the logits are '
              'nearest-upsampled. That caps per-class IoU for a one-pixel target and is the main '
              'reason its mIoU is low -- see `exp03/summaries/width025_d32.json`, where a stride-1 '
              'head at this grid (width 0.25) scores 0.4919 +- 0.0730 against this configuration\'s '
              '0.3212 +- 0.0307.']
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    for pkg in sys.argv[1:]:
        pkg = pkg.rstrip('/')
        open(f'{pkg}/README.md', 'w').write(readme(pkg))
        print('wrote', f'{pkg}/README.md')
